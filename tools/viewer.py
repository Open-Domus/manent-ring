"""Write view.html: one page to look at the schematic, the board layer by layer and the
mechanical drawings in a browser.   uv run python tools/viewer.py && xdg-open view.html"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LAYERS = [("F.Cu", "1 · top, towards the titanium"), ("In1.Cu", "2"), ("In2.Cu", "3 · ground plane, crosses the bends"),
          ("In3.Cu", "4 · signals, crosses the bends"), ("In4.Cu", "5"), ("B.Cu", "6 · bottom, towards the finger")]
ISLANDS = ["contacts", "button", "soc", "audio", "storage", "power", "antenna"]

layers = "".join(f'<img class="layer" id="L{i}" src="electrical/out/board-{name}.svg" alt="layer {name}">'
                 for i, (name, _) in enumerate(LAYERS))
toggles = "".join(f'<label><input type="checkbox" data-l="L{i}" {"checked" if i in (0, 5) else ""}> {text}</label>'
                  for i, (_, text) in enumerate(LAYERS))
sections = "".join(f'<figure><img src="mechanical/out/section-B-{n}.svg" alt="{n}"><figcaption>{n}</figcaption></figure>'
                   for n in ISLANDS)
renders = "".join(f'<figure><img src="electrical/out/render-{s}.png" alt="{s}"><figcaption>{s}</figcaption></figure>'
                  for s in ("top", "bottom") if (ROOT / "electrical" / "out" / f"render-{s}.png").exists())

html = f"""<!doctype html>
<html lang="en"><meta charset="utf-8"><title>Manent ring: hardware</title>
<style>
  body {{ font: 15px/1.5 system-ui, sans-serif; margin: 0 auto; max-width: 1200px; padding: 16px; color: #222; background: #fafafa; }}
  h1 {{ font-size: 22px; }} h2 {{ font-size: 17px; margin-top: 36px; border-top: 1px solid #ccc; padding-top: 16px; }}
  .board {{ position: relative; background: #fff; border: 1px solid #ccc; overflow: auto; }}
  .board img.layer {{ position: absolute; left: 0; top: 0; width: 100%; mix-blend-mode: multiply; }}
  .board img.layer:first-child {{ position: relative; }}
  .toggles label {{ display: inline-block; margin: 6px 14px 6px 0; }}
  .row {{ display: flex; flex-wrap: wrap; gap: 12px; }}
  figure {{ margin: 0; background: #fff; border: 1px solid #ccc; padding: 6px; flex: 1 1 320px; }}
  figure img {{ width: 100%; }} figcaption {{ font-size: 13px; color: #555; text-align: center; }}
  input[type=range] {{ width: 260px; vertical-align: middle; }}
  a {{ color: #0a58ca; }}
</style>
<h1>Manent ring: hardware</h1>
<p>Generated by <code>tools/viewer.py</code> from the files in this repository. Nothing here is measured or built.</p>

<h2>Board, layer by layer</h2>
<p>Seen from the top (the titanium side). X runs along the ring from the cell tabs; the vertical lines are the
edges of the islands and of the bends. Zoom: <input type="range" id="zoom" min="100" max="600" value="100"> </p>
<div class="toggles">{toggles}</div>
<div class="board"><div id="stack" style="position:relative;width:100%">{layers}</div></div>

{'<h2>Board, rendered</h2><div class="row">' + renders + '</div>' if renders else ''}

<h2>Ring, seen along the finger</h2>
<div class="row"><figure><img src="mechanical/out/plan-B.svg" alt="plan"><figcaption>8.0 mm band: islands and cell around the ring</figcaption></figure></div>

<h2>Cross-sections through each island</h2>
<div class="row">{sections}</div>

<h2>Documents</h2>
<ul>
  <li><a href="electrical/out/schematic.pdf">Schematic (PDF)</a></li>
  <li><a href="electrical/out/bom.csv">Bill of materials (CSV)</a></li>
  <li><a href="docs/design.md">Design</a> · <a href="docs/space-budget.md">Space budget</a> ·
      <a href="docs/power-budget.md">Power budget</a> · <a href="docs/open-questions.md">Open questions</a> ·
      <a href="docs/fabricators.md">Fabricators</a></li>
  <li>3D models: <code>mechanical/out/ring-B.step</code> and the <code>print-*.stl</code> files open in any CAD or slicer.</li>
</ul>
<script>
  const show = () => document.querySelectorAll('input[data-l]').forEach(c =>
    document.getElementById(c.dataset.l).style.display = c.checked ? '' : 'none');
  document.querySelectorAll('input[data-l]').forEach(c => c.addEventListener('change', show));
  document.getElementById('zoom').addEventListener('input', e =>
    document.getElementById('stack').style.width = e.target.value + '%');
  show();
</script>
</html>
"""
(ROOT / "view.html").write_text(html)
print("view.html written")
